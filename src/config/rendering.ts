/**
 * WebGL 上下文的 GPU 偏好。
 *
 * 这是给浏览器的**请求**，不是命令。
 *
 * 不给提示时 Three.js 的默认值是 `'default'`，也就是「由浏览器决定」。
 * 在核显 + 独显的双显卡笔记本上，浏览器经常把 WebGL 上下文交给核显，
 * 帧率直接掉一半——这不是本项目的 bug，但用这个项目的人会以为它卡。
 *
 * 请求 `'high-performance'` 能明显提高拿到独显的概率。代价是插电时耗电略高。
 *
 * ⚠️ 请求不等于保证。浏览器也可能因为驱动被列入黑名单、系统的「图形性能」
 * 设置成省电、或者页面落在软件渲染名单里而不给独显。要确认实际拿到哪块显卡，
 * 运行时读 `WEBGL_debug_renderer_info` 的渲染器型号。
 *
 * ⚠️ 离线缩略图脚本（`scripts/render-model-thumbnails.mjs`）不受这条约束：
 * 它在无头 Chrome 里做一次性渲染，产物是静态 PNG，选哪块显卡没有用户可见的影响。
 */
export const RENDER_POWER_PREFERENCE = 'high-performance' as const
