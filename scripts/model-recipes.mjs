/**
 * 内置模型的几何配方。
 *
 * 每个模型是一组「零件」：基本体 + 位置 + 旋转 + 颜色。
 * 生成器按配方在内存里拼装，导出 GLB，再由 render-model-thumbnails.mjs
 * 从**导出的文件**渲染缩略图——保证卡片上的图就是点进去加载到的东西。
 *
 * 配色说明：
 * UI 的令牌层（DESIGN.md）管的是界面文字与背景，3D 物件不受 WCAG 文字对比度约束，
 * 但仍然沿用同一套主色，避免模型库和全站视觉脱节：
 *   #6E5AF0 靛紫主色 · #4B37C9 深靛 · #333333 深灰 · #666666 中灰
 *   #FFA117 琥珀高光（自发光）· #3498DB 青色（自发光）· #E4E9F5 浅灰
 * 材质色里另有几个是 3D 内容必需的（树绿、树皮棕），只存在于模型里。
 */

/**
 * 几何体参数表：
 *   box       [w, h, d]
 *   cylinder  [r, h]                 h 沿 Y 轴
 *   cone      [r, h]                 h 沿 Y 轴
 *   torus     [r, tube]
 *   icosa     [r]                    二十面体（岩石、灌木）
 *   plane     [w, d]                 法线朝 +Y
 *
 * 圆柱与锥体参数相同，用 cone 标记区分——生成器靠它决定建哪种几何体。
 */
